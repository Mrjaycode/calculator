function calcDiscount(){

let price = parseFloat(document.getElementById("price").value) || 0;
let discount = parseFloat(document.getElementById("discount").value) || 0;
let qty = parseFloat(document.getElementById("qty").value) || 1;

let discountAmount = (price * discount / 100) * qty;
let finalPrice = (price * qty) - discountAmount;

document.getElementById("save").innerHTML = "₹" + discountAmount.toFixed(2);
document.getElementById("final").innerHTML = "₹" + finalPrice.toFixed(2);

}

