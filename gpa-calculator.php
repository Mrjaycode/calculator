document.getElementById("points").addEventListener("input", calculateGPA);
document.getElementById("credits").addEventListener("input", calculateGPA);

function calculateGPA(){

let points = parseFloat(document.getElementById("points").value) || 0;
let credits = parseFloat(document.getElementById("credits").value) || 0;

if(credits == 0){
document.getElementById("gparesult").innerHTML = "0.00";
document.getElementById("gpa").value = "";
return;
}

let gpa = points / credits;

document.getElementById("gparesult").innerHTML = gpa.toFixed(2);
document.getElementById("gpa").value = gpa.toFixed(2);

}

