<script>
let current = "";
let operator = "";
let previous = "";

function updateDisplay() {
  document.getElementById("mcDisp").innerText = current || "0";
  document.getElementById("mcPrev").innerText =
    previous && operator ? previous + " " + operator : "";
}

function press(num) {
  if (current === "Error") current = "";
  current += num;
  updateDisplay();
}

function setOperator(op) {
  if (current === "") return;

  if (previous !== "") {
    calculate();
  }

  operator = op;
  previous = current;
  current = "";
  updateDisplay();
}

function calculate() {
  let a = parseFloat(previous);
  let b = parseFloat(current);
  let result;

  if (isNaN(a) || isNaN(b)) return;

  switch (operator) {
    case "+": result = a + b; break;
    case "-": result = a - b; break;
    case "*": result = a * b; break;
    case "/": result = b !== 0 ? a / b : "Error"; break;
  }

  current = result.toString();
  operator = "";
  previous = "";
  updateDisplay();
}

function clearCalc() {
  current = "";
  previous = "";
  operator = "";
  updateDisplay();
}

function backspace() {
  current = current.slice(0, -1);
  updateDisplay();
}

function percent() {
  if (current !== "") {
    current = (parseFloat(current) / 100).toString();
    updateDisplay();
  }
}

function toggleSign() {
  if (current !== "") {
    current = (parseFloat(current) * -1).toString();
    updateDisplay();
  }
}

/* KEYBOARD SUPPORT 🔥 */
document.addEventListener("keydown", (e) => {
  if (!isNaN(e.key) || "+-*/.".includes(e.key)) {
    press(e.key);
  } else if (e.key === "Enter") {
    calculate();
  } else if (e.key === "Backspace") {
    backspace();
  }
});
</script>
