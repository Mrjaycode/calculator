function heroCalcEMI() {
  var P = parseFloat(document.getElementById('heroAmt').value) || 0;
  var r = parseFloat(document.getElementById('heroRate').value) / 100 / 12 || 0;
  var n = parseFloat(document.getElementById('heroTenure').value) * 12 || 0;
 
  if (!P || !r || !n) {
    document.getElementById('heroEmiVal').textContent = '—';
    document.getElementById('heroInterest').textContent = '—';
    document.getElementById('heroTotal').textContent = '—';
    return;
  }
 
  function fmt(v) { return Math.round(v).toLocaleString('en-IN'); }
 
  var emi = P * r * Math.pow(1 + r, n) / (Math.pow(1 + r, n) - 1);
  var total = emi * n;
  var interest = total - P;
 
  document.getElementById('heroEmiVal').textContent   = fmt(emi);
  document.getElementById('heroInterest').textContent = '₹' + fmt(interest);
  document.getElementById('heroTotal').textContent    = '₹' + fmt(total);
  document.getElementById('heroBkP').style.width      = (P / total * 100).toFixed(1) + '%';
}
 
heroCalcEMI();
