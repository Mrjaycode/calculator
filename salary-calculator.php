let pf = parseFloat(document.getElementById("pf").value) || 0;
let tax = parseFloat(document.getElementById("tax").value) || 0;

let pfAmount = (gross * pf) / 100;
let taxAmount = (gross * tax) / 100;

let net = gross - pfAmount - taxAmount;

document.getElementById("pfAmount").innerHTML = "₹" + pfAmount.toFixed(2);
document.getElementById("taxAmount").innerHTML = "₹" + taxAmount.toFixed(2);
document.getElementById("netSalary").innerHTML = "₹" + net.toFixed(2);

}

