function calculateEMI(){

let P = parseFloat(document.getElementById("loan").value) || 0;
let annualRate = parseFloat(document.getElementById("rate").value) || 0;
let N = parseFloat(document.getElementById("months").value) || 0;

let R = annualRate / 12 / 100;

let EMI = 0;

if(R > 0 && N > 0){
EMI = (P * R * Math.pow(1+R,N)) / (Math.pow(1+R,N)-1);
}

let totalPayment = EMI * N;
let totalInterest = totalPayment - P;

document.getElementById("emi").innerHTML = "₹" + EMI.toFixed(2);
document.getElementById("interest").innerHTML = "₹" + totalInterest.toFixed(2);
document.getElementById("payment").innerHTML = "₹" + totalPayment.toFixed(2);

}

